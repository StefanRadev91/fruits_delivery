const VAT = 1.2;

/** Supplier price without VAT in cents (derived from the VAT price when only that is given). */
export function supplierNetCents(row: Row): number {
  const [, , net, gross] = row;
  if (net != null) return Math.round(net * 100);
  return Math.round((gross! * 100) / VAT);
}

/** Our base price without VAT in cents: supplier price minus our reduction. */
export function ourNetCents(row: Row, reductionPercent = OUR_REDUCTION_PERCENT): number {
  return Math.round((supplierNetCents(row) * (100 - reductionPercent)) / 100);
}

/** True when the supplier's two price columns don't match a 20% VAT (likely a typo in the list). */
export function vatLooksOff(row: Row): boolean {
  const [, , net, gross] = row;
  if (net == null || gross == null) return false;
  return Math.abs(gross / net - VAT) > 0.07;
}
